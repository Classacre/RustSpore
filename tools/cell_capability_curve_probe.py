from cell_schema_probe import SourceImage, SOURCE_SHA256
from cell_native_math_probe import db, IMPORTS

CODE = [(0xe837f0, 0xe8393c), (0x1041e40, 0x1041e57)]
EPSILON = 0x149a808
PROVIDER = 0x67d950
INPUT_BYTES = 160
OUTPUT_BYTES = 16


def audit(image):
    sys.path.insert(0,str(Path(__file__).resolve().parent.parent/'target/rea/capstone-runtime'))
    from capstone import Cs,CS_ARCH_X86,CS_MODE_32,CS_GRP_CALL,CS_GRP_JUMP
    from capstone.x86 import X86_OP_IMM,X86_OP_MEM,X86_OP_REG
    decoder=Cs(CS_ARCH_X86,CS_MODE_32);decoder.detail=True
    records=[]
    indirect_sites={0xe83818,0xe8382d,0xe83841,0xe83861,0xe838b0,0xe838e9}
    found=set()
    for start,end in CODE:
        decoded=list(decoder.disasm(image.read(start,end-start),start))
        assert sum(i.size for i in decoded)==end-start
        calls=[];indirect=[];memory=[]
        for ins in decoded:
            if ins.group(CS_GRP_CALL) or ins.group(CS_GRP_JUMP):
                operand=ins.operands[0]
                if operand.type==X86_OP_IMM:
                    target=operand.imm
                    if ins.group(CS_GRP_CALL):
                        assert target in {PROVIDER,0x1041e40}
                        calls.append(dict(at=f'{ins.address:08X}',target=f'{target:08X}'))
                    else:assert start<=target<end
                else:
                    assert ins.group(CS_GRP_CALL) and operand.type==X86_OP_REG
                    assert ins.address in indirect_sites
                    found.add(ins.address)
                    indirect.append(dict(at=f'{ins.address:08X}',operand=ins.op_str))
            for operand in ins.operands:
                if operand.type!=X86_OP_MEM:continue
                if operand.mem.base==0:
                    assert operand.mem.index==0 and operand.mem.disp==EPSILON
                memory.append(ins.op_str)
        records.append(dict(start=f'{start:08X}',end_exclusive=f'{end:08X}',
            bytes=end-start,sha256=hashlib.sha256(image.read(start,end-start)).hexdigest(),
            direct_calls=calls,checked_vtable_calls=indirect,
            memory_operands=sorted(set(memory)),
            disassembly=[f'{i.address:08X}: {i.mnemonic} {i.op_str}'for i in decoded]))
    assert found==indirect_sites
    assert image.read(EPSILON,4)==struct.pack('<I',0x37800000)
    return records


