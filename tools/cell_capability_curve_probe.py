def linked_provider_audit(exe,map_path):
    symbols={}
    wanted={'FakeManager','FakeList','ManagerVtable','ListVtable','ManagerLookup','GetProperty','ListRelease','HostFailure','ManagerProvider'}
    for line in map_path.read_text().splitlines():
        match=re.match(r'\s*[0-9A-Fa-f]{4}:[0-9A-Fa-f]{8}\s+(\w+)\s+([0-9A-Fa-f]{8})\b',line)
        if match and match[1] in wanted:symbols[match[1]]=int(match[2],16)
    assert set(symbols)==wanted,symbols
    stub=b'\xb8'+struct.pack('<I',symbols['FakeManager'])+b'\xc3'
    raw=exe.read_bytes();pe=struct.unpack_from('<I',raw,60)[0]
    base=struct.unpack_from('<I',raw,pe+52)[0]
    count=struct.unpack_from('<H',raw,pe+6)[0]
    optional=struct.unpack_from('<H',raw,pe+20)[0]
    sections=[]
    for index in range(count):
        at=pe+24+optional+40*index
        _,rva,size,offset=struct.unpack_from('<4I',raw,at+8)
        flags=struct.unpack_from('<I',raw,at+36)[0]
        sections.append((base+rva,size,offset,flags))
    def read(address,size):
        for start,length,offset,flags in sections:
            if start<=address and address+size<=start+length:
                at=offset+address-start
                return raw[at:at+size],flags
        raise ValueError(f'unmapped_host_symbol{address:08X}')
    for label in ['FakeManager','FakeList','ManagerVtable','ListVtable']:
        _,flags=read(symbols[label],4)
        assert flags&0x40000000 and not flags&0x80000000
    assert symbols['ManagerProvider']==PROVIDER
    actual_stub,stub_flags=read(PROVIDER,6)
    assert actual_stub==stub and stub_flags&0x60000000==0x60000000 and not stub_flags&0x80000000
    assert struct.unpack('<I',read(symbols['FakeManager'],4)[0])[0]==symbols['ManagerVtable']
    assert struct.unpack('<I',read(symbols['FakeList'],4)[0])[0]==symbols['ListVtable']
    assert struct.unpack('<I',read(symbols['ManagerVtable']+0x2c,4)[0])[0]==symbols['ManagerLookup']
    assert struct.unpack('<I',read(symbols['ListVtable']+4,4)[0])[0]==symbols['ListRelease']
    assert struct.unpack('<I',read(symbols['ListVtable']+0x28,4)[0])[0]==symbols['GetProperty']
    return dict(symbols={name:f'{value:08X}'for name,value in symbols.items()},
        provider_stub_address=f'{PROVIDER:08X}',provider_stub_hex=stub.hex(),
        provider_stub_sha256=hashlib.sha256(stub).hexdigest(),provider_stub_outbound_relative_transfers=0,
        provider_compiled_in_host_image=True,provider_section_RX_not_writable=True,
        immutable_objects_and_vtables=True,
        vtable_call_proof={
            'E83818':'Initial local reference is literal NULL, so cleanup call is unreachable.',
            'E8382D':'67D950 returns immutable FakeManager; vtable+2C is checked ManagerLookup.',
            'E83841':'ManagerLookup writes only NULL/FakeList to the exact native reference stack slot; vtable+28 is checked GetProperty.',
            'E83861/E838B0/E838E9':'Non-NULL native reference is immutable FakeList; vtable+4 is checked ListRelease.'},
        bounds_proof='ManagerLookup validates this, instanceC951EB63, scope0 and exact stack-slot output address. GetProperty validates this and requested caller property ID. Counts are0..16, inline counts0..1, and native data pointers are only the bounded input rows or the fixed20-byte inline object. All writes stay in the native stack slot, host counters/output, or guarded input/property buffers. Input cannot provide pointers or vtable entries.')


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('exe',type=Path)
    ap.add_argument('--sdk-bin-x86',type=Path,required=True)
    ap.add_argument('--kernel32-lib',type=Path,required=True)
    ap.add_argument('--out',type=Path,required=True)
    args=ap.parse_args()
    args.out.resolve().relative_to((Path(__file__).resolve().parent.parent/'target').resolve())
    image=SourceImage(args.exe)
    records=audit(image)
    source,code_pages,pages=host_source(image)
    args.out.mkdir(parents=True,exist_ok=False);out=args.out.resolve()
    assembly=out/'host-x86.asm';obj=out/'host-x86.obj';exe=out/'host-x86.exe';mapping=out/'host-x86.map'
    assembly.write_text(source)
    for command in [
        [str(args.sdk_bin_x86/'ml.exe'),'/nologo','/c','/coff',f'/Fo{obj}',str(assembly)],
        [str(args.sdk_bin_x86/'link.exe'),'/NOLOGO','/MACHINE:X86','/SUBSYSTEM:CONSOLE',
            '/ENTRY:HostMain','/BASE:0x00670000','/DYNAMICBASE:NO','/SAFESEH:NO',
            f'/OUT:{exe}',f'/MAP:{mapping}',str(obj),str(args.kernel32_lib)],
    ]:
        result=subprocess.run(command,capture_output=True,text=True)
        assert result.returncode==0,result.stdout+'\n'+result.stderr
    manifest=dict(source_sha256=SOURCE_SHA256,host_executed=False,host_image_base='00670000',
        code_allowlist=records,data_allowlist=[dict(address=f'{EPSILON:08X}',bytes=4,word='37800000',
            sha256=hashlib.sha256(image.read(EPSILON,4)).hexdigest())],
        replacement_provider=linked_provider_audit(exe,mapping),
        imported_host_functions=IMPORTS,
        pages=[dict(address=f'{page:08X}',bytes=65536,protection='RWX' if page in code_pages else 'RW')for page in sorted(pages)],
        protocol=dict(input_bytes=INPUT_BYTES,output_bytes=OUTPUT_BYTES,max_points=16,
            input_fields=['property_id:u32@0','query:f32@4','count:u32@8','CW:u16@12',
                'reserved@14..15','mode:u32@16 (0missinglist,1array,2inline)','reserved@20..31',
                'points@32:16*Vector2f32; count active, inline count0/1, missing count0'],
            output_fields=['value:f32@0','manager_lookup_count:u32@4','property_get_count:u32@8','release_count:u32@12']),
        setup_failure_exit_codes={str(ordinal):f'VirtualAlloc exact page{page:08X}'for ordinal,page in enumerate(sorted(pages),10)}|{'20':'FlushInstructionCache','7':'Protocol/provider/buffer guard'},
        host_source_sha256=hashlib.sha256(assembly.read_bytes()).hexdigest(),
        host_exe_sha256=hashlib.sha256(exe.read_bytes()).hexdigest(),
        scope='Original E837F0 plus1041E40; checked mock property providers only. No game initialization, retail process, live manager, actor, window or network.')
    (out/'manifest.json').write_text(json.dumps(manifest,indent=2))
    print(json.dumps({name:manifest[name]for name in ['source_sha256','host_executed','host_source_sha256','host_exe_sha256']},indent=2))


if __name__=='__main__':main()
