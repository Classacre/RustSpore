"""Prepare, but do not execute, the original E837F0 property-curve host.

The only native code is the complete evaluator and 1041E40. A checked mock
property provider supplies bounded Vector2 rows. No game initializer, live
property manager, actor, retail process or desktop interaction is involved.
Every generated byte/host/audit remains ignored under target/.
"""
import argparse
