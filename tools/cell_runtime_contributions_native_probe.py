def linked_audit(path, mapping, image):
    pe = PE(path)
    symbols = {}
    for line in mapping.read_text().splitlines():
        match = re.match(r'\s*[0-9A-Fa-f]{4}:[0-9A-Fa-f]+\s+(\S+)\s+([0-9A-Fa-f]{8})\b', line)
        if match:
            symbols[match[1]] = int(match[2], 16)
    assert pe.base == 0x26000000
    first, last = symbols['OwnedStart'], symbols['OwnedEnd']
    rows = list(decoder().disasm(pe.read(first, last-first), first))
    assert sum(row.size for row in rows) == last-first
    boundaries = {row.address for row in rows}
    imports = pe.imports()
    assert {name for dll, name in imports.values() if dll.lower() == 'kernel32.dll'} == IMPORTS and len(imports) == 8
    from capstone import CS_GRP_CALL, CS_GRP_JUMP
    from capstone.x86 import X86_OP_IMM
    for row in rows:
        if row.group(CS_GRP_CALL) or row.group(CS_GRP_JUMP):
            assert row.operands[0].type == X86_OP_IMM
            target = row.operands[0].imm
            if target not in boundaries:
                thunk = pe.read(target, 6)
                assert row.mnemonic == 'call' and thunk[:2] == b'\xFF\x25'
                assert struct.unpack_from('<I', thunk, 2)[0] in imports
    at = struct.unpack_from('<I', pe.data, 0x3C)[0]
    count, optional = struct.unpack_from('<H', pe.data, at+6)[0], struct.unpack_from('<H', pe.data, at+20)[0]
    sections = []
    for i in range(count):
        row = at+24+optional+40*i
        size, rva = struct.unpack_from('<II', pe.data, row+8)
        sections.append((pe.base+rva, pe.base+rva+size, struct.unpack_from('<I', pe.data, row+36)[0]))
    def flags(address, size):
        return next(value for low, high, value in sections if low <= address and address+size <= high) & 0xE0000000
    assert flags(first, last-first) == 0x60000000
    for a, b in CODE:
        location = symbols[f'Original_{a:08X}']
        assert pe.read(location, b-a) == image.read(a, b-a) and flags(location, b-a) == 0x40000000
    extents = []
    for name, size in BUFFERS:
        address = symbols[name+'Buffer']
        assert address-symbols[name+'Before'] == 16 and symbols[name+'After']-address == size
        assert flags(address-16, size+32) == 0xC0000000
        assert all(address+size+16 <= low or high <= address-16 for low, high in extents)
        extents.append((address-16, address+size+16))
    return dict(host_exe_sha256=digest(pe.data), owned_code_sha256=digest(pe.read(first, last-first)),
        symbols={name:f'{value:08X}' for name,value in symbols.items() if not name.startswith('_')},
        imports=[dict(iat=f'{address:08X}', dll=dll, name=name) for address,(dll,name) in imports.items()],
        source_bytes_exact=True, section_permissions_checked=True, buffers_nonoverlapping=True,
        disassembly=[f'{row.address:08X}: {row.bytes.hex()} {row.mnemonic} {row.op_str}' for row in rows])


