def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def audit_source(image):
    sys.path.insert(0, str(ROOT/'target/rea/capstone-runtime'))
    from capstone import CS_GRP_CALL, CS_GRP_JUMP
    from capstone.x86 import X86_OP_IMM, X86_OP_MEM
    decoded = {a: list(decoder().disasm(image.read(a, b-a), a)) for a, b in CODE}
    boundaries = {row.address for rows in decoded.values() for row in rows}
    records = []
    for first, last in CODE:
        rows = decoded[first]
        assert sum(row.size for row in rows) == last-first
        transfers = []
        for row in rows:
            if row.group(CS_GRP_CALL) or row.group(CS_GRP_JUMP):
                assert row.operands[0].type == X86_OP_IMM
                target = row.operands[0].imm
                assert target in boundaries or target in EXITS
                if row.group(CS_GRP_CALL):
                    assert (row.address, target) == (0x99DD0F, 0x99C170)
                transfers.append(dict(at=f'{row.address:08X}', operation=row.mnemonic, target=f'{target:08X}'))
            for op in row.operands:
                if op.type == X86_OP_MEM:
                    assert op.mem.base or op.mem.index
        records.append(dict(start=f'{first:08X}', end_exclusive=f'{last:08X}', bytes=last-first,
            sha256=digest(image.read(first, last-first)), transfers=transfers, absolute_data_dependencies=0,
            disassembly=[f'{row.address:08X}: {row.bytes.hex()} {row.mnemonic} {row.op_str}' for row in rows]))
    assert image.read(0x99DC93, 4) == bytes.fromhex('a8407450')
    return records


